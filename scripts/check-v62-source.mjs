import assert from 'node:assert/strict';
import { readFile, stat } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFile(resolve(root,p),'utf8');
const about = await read('src/pages/pages.tsx');
const aboutData = await read('src/data/about.ts');
const meetfolio = await read('src/pages/cases/Meetfolio.tsx');
const css = await read('src/styles/main.css');
assert(about.includes('Hi!<br />I am <em>Martin Zhong.</em>'), 'New About title missing');
for(const q of ['QS 2027 #36','QS 2027 =258','First Prize Scholarship','Second Prize Scholarship']) assert(about.includes(q),q);
for(const q of ['Sun Yat-sen University','Shanghai Jiao Tong University','2025.09','2021.09']) assert(about.includes(q),q);
for(const q of ['meetfolio/workspace-demo-20261027.webp','https://github.com/MartinZhong2026/meetfolio']) assert(meetfolio.includes(q),q);
assert(about.includes('<figcaption><span>{photo.title}</span></figcaption>'), 'Transparent photo-caption markup missing');
assert(css.includes('.about-v6__gallery .about-v6__photo::after { display:none; }'),'Photo overlay removal missing');
assert(aboutData.includes("className: 'hiking', publicOk: true") && aboutData.includes("className: 'wide', publicOk: true"),'Five photo gallery missing');
for(const img of ['public/assets/meetfolio/workspace-demo-20261027.webp','public/assets/about/martin-shanghai-night.jpg','public/assets/about/jingan-10k.jpg','public/assets/about/hong-kong-sketch.jpg','public/assets/about/hiking-group.jpg','public/assets/about/shanghai-run-group.jpg']) await stat(resolve(root,img));
assert(!/CCTV|government internship|government project/i.test(about+aboutData),'Excluded experience appeared in About content');
console.log('PASS: V6.2 About title, education, rankings, scholarships, five gallery photos, Meetfolio screenshot and link, excluded roles.');
