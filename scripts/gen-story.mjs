// Generates src/data/story.ts from the approved copy in scripts/fixtures/about-story.md,
// so the page text cannot drift from the approved version. Run after editing the fixture.
import { readFile, writeFile } from 'node:fs/promises';

const md = (await readFile(new URL('./fixtures/about-story.md', import.meta.url), 'utf8')).replace(/\r\n/g, '\n').trim();
const blocks = md.split(/\n\n+/);
const heading = blocks.shift().replace(/^## /, '');
const question = blocks.shift().replace(/^### /, '');
const out = `// GENERATED by scripts/gen-story.mjs from scripts/fixtures/about-story.md. Do not edit by hand.
// This is Martin's approved essay: do not rewrite, shorten or add to it.
export const story = ${JSON.stringify({ heading, question, paragraphs: blocks }, null, 2)} as const;
`;
await writeFile(new URL('../src/data/story.ts', import.meta.url), out);
console.log(`story.ts written: ${blocks.length} paragraphs`);
